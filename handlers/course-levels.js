const keyboardFor = (course) => ({
  inline_keyboard: [
    [{ text: "💬 Узнать подробнее", callback_data: `ask-${course.id}` }],
    [{ text: "⬅️ Назад", callback_data: course.back }],
    [{ text: "🏠 Главное меню", callback_data: "menu" }],
  ],
});

// callback_data -> обработчик: страница курса и кнопка «Узнать подробнее»
export const COURSE_HANDLERS = Object.fromEntries(
  COURSES.flatMap((course) => [
    [course.id, (ctx) => ctx.send(course.text, keyboardFor(course))],
    [`ask-${course.id}`, (ctx) => handleCourseInquiry(ctx, course.title)],
  ]),
);
